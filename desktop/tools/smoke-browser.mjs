const FIXTURE_LABEL = "coffee-bar-wait-times.csv (24 rows)"; // must match source_filename + row_count exactly
const FIXTURE_PNG_PATH = path.join(SCRIPT_DIR, "fixtures", "floorplan-fixture.png"); // 700x550, generated by a stdlib-only Python script (see build report)
// Milestone-4 (T-20 Before/After Proof): before/after scrap-rate fixtures,
// same values as engine/tests/factories.py's make_proof() -- one dataset
// threaded through both the engine tests and this live smoke run.
const FIXTURE_SCRAP_BEFORE_PATH = path.join(SCRIPT_DIR, "fixtures", "scrap-rate-before.csv");
const FIXTURE_SCRAP_AFTER_PATH = path.join(SCRIPT_DIR, "fixtures", "scrap-rate-after.csv");

const steps = [];
const pageErrors = [];
const consoleErrors = [];

function log(status, name, detail) {
  const line = `[${status}] ${name}${detail ? " -- " + detail : ""}`;
  console.log(line);
  steps.push({ status, name, detail });
}

async function step(name, fn) {
  try {
    await fn();
    log("PASS", name);
  } catch (err) {
    log("FAIL", name, err instanceof Error ? err.message : String(err));
    throw err;
  }
}

function assert(condition, message) {
  if (!condition) throw new Error(message);
}

// Strips everything but digits/./- so "6,000" or "Total: 9,600" reads as a
// plain number, regardless of the browser's thousands-separator locale.
function numeric(text) {
  if (text == null) return NaN;
  return Number(text.replace(/[^\d.-]/g, ""));
}

