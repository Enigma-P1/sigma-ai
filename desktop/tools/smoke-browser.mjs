      await page.locator('[data-testid="controlchart-imr-source-column"]').selectOption("wait_seconds");
      assert(await page.locator('[data-testid="controlchart-freeze"]').isEnabled(), "Freeze button should be enabled once metric + data are set");
      await page.locator('[data-testid="controlchart-freeze"]').click();
